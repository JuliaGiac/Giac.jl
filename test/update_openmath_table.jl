# Embed the giac-openmath table at a commit into ext/giac_openmath_table.jl, and
# its shared corpus into test/giac_openmath_corpus.jl:
#
#     julia test/update_openmath_table.jl <commit>
#
# The table (https://github.com/JuliaGiac/giac-openmath) is data, kept in its
# own repository; GiacOpenMathExt reads the copy embedded here, and the
# extension's tests compare it with the file at that commit.

using Downloads, SHA

commit = only(ARGS)
occursin(r"^[0-9a-f]{40}$", commit) || error("give the full 40-character commit")
url = "https://raw.githubusercontent.com/JuliaGiac/giac-openmath/$commit/giac-openmath.toml"
toml = String(take!(Downloads.download(url, IOBuffer())))
occursin("\"\"\"", toml) && error("the table holds \"\"\", which the raw string cannot")

path = joinpath(dirname(@__DIR__), "ext", "giac_openmath_table.jl")
open(path, "w") do io
    println(io, "# The giac-openmath table, embedded: generated by test/update_openmath_table.jl.")
    println(io, "# Source: https://github.com/JuliaGiac/giac-openmath/blob/$commit/giac-openmath.toml")
    println(io, "# Do not edit by hand: change the table there, then run the script with its commit.")
    println(io)
    println(io, "const TABLE_COMMIT = \"$commit\"")
    println(io, "const TABLE_SHA256 = \"$(bytes2hex(sha256(toml)))\"")
    println(io, "const TABLE_TOML = raw\"\"\"")
    print(io, toml)
    println(io, "\"\"\"")
end
println("wrote ", path)

# the shared corpus at the same commit, which the extension's tests read
corpus = String(take!(Downloads.download(
    "https://raw.githubusercontent.com/JuliaGiac/giac-openmath/$commit/test/fixtures/openmath-to-giac.json", IOBuffer())))
(occursin("\"\"\"", corpus) || occursin('\\', corpus)) &&
    error("the corpus holds \"\"\" or a backslash, which the raw string cannot")
corpus_path = joinpath(@__DIR__, "giac_openmath_corpus.jl")
open(corpus_path, "w") do io
    println(io, "# The shared corpus of giac-openmath, embedded: generated by test/update_openmath_table.jl.")
    println(io, "# Source: https://github.com/JuliaGiac/giac-openmath/blob/$commit/test/fixtures/openmath-to-giac.json")
    println(io)
    println(io, "const CORPUS_JSON = raw\"\"\"")
    print(io, corpus)
    println(io, "\"\"\"")
end
println("wrote ", corpus_path)
